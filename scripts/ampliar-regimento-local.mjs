import {createRequire} from 'node:module';
import {readFileSync,writeFileSync,copyFileSync} from 'node:fs';
import {resolve} from 'node:path';
import {createHash} from 'node:crypto';
const require=createRequire(resolve('../sylvinho-backend/functions/package.json'));
const {extrairPdf}=require('./ingestao/extrairPdf.js');
const {prepararIngestao}=require('./ingestao/documentosOficiais.js');
const base=JSON.parse(readFileSync('.cache/chat-rag/base.json','utf8'));
const sources=JSON.parse(readFileSync('.cache/chat-rag/fontes.json','utf8'));
const source=sources.find(s=>s.id==='regimento-comum-87-2022');
const file=resolve('.cache/chat-rag',source.arquivo);
if(createHash('sha256').update(readFileSync(file)).digest('hex')!==source.sha256)throw Error('HASH_DIVERGENTE');
const pages=(await extrairPdf(file)).map(p=>({...p,texto:p.texto.split('\n').filter(line=>!/^D\.O\.E\.;|^Página \d+ de \d+$/u.test(line.trim())).join('\n')}));
const result=prepararIngestao({titulo:source.titulo,tipo:'regimento',documentoId:source.id,versao:source.sha256,arquivo:source.arquivo,ativo:true},pages,{maxCaracteres:420,classificarConteudo:true});
const chunks=result.chunks.filter(c=>/Art(?:igo)?\.?\s*\d/iu.test(c.secao+' '+c.titulo)).map((c,i)=>({...c,id:'regimento-integral-'+i,fonteUrl:source.url,fonteSha256:source.sha256,formaExtracao:'extração do PDF por artigo; snapshot local, vigência não certificada'}));
if(!base.some(c=>c.id.startsWith('regimento-integral-')))copyFileSync('.cache/chat-rag/base.json','.cache/chat-rag/base-antes-ampliacao.json');
writeFileSync('.cache/chat-rag/base.json',JSON.stringify([...base.filter(c=>c.documentoId!==source.id),...chunks],null,2));
writeFileSync('.cache/chat-rag/ampliacao.json',JSON.stringify({paginas:pages.length,chunks:chunks.length,fonte:source.url,sha256:source.sha256},null,2));
console.log(JSON.stringify({paginas:pages.length,chunksRegimento:chunks.length,total:base.filter(c=>c.documentoId!==source.id).length+chunks.length}));
